// Interpolación / búsqueda del valor de avance en tabla por diámetro
function interpolarPorDiametro(diam, diamsArr, valoresArr) {
    if (!valoresArr || !valoresArr.length) return null;
    if (diam <= diamsArr[0]) return valoresArr[0];
    if (diam >= diamsArr[diamsArr.length - 1]) return valoresArr[valoresArr.length - 1];
    for (let i = 0; i < diamsArr.length - 1; i++) {
        if (Math.abs(diam - diamsArr[i]) < 1e-3) return valoresArr[i];
        if (diam > diamsArr[i] && diam < diamsArr[i + 1]) {
            const t = (diam - diamsArr[i]) / (diamsArr[i + 1] - diamsArr[i]);
            return Number((valoresArr[i] + t * (valoresArr[i + 1] - valoresArr[i])).toFixed(3));
        }
    }
    return valoresArr[valoresArr.length - 1];
}

// Parsea un código de celda Dormer (ej: "110A" -> { vc: 110, letra: "A" })
function parseDormerCode(str) {
    if (!str) return null;
    const m = String(str)
        .trim()
        .match(/^(\d+(?:\.\d+)?)\s*([A-Z])$/i);
    if (!m) return null;
    return { vc: parseFloat(m[1]), letra: m[2].toUpperCase() };
}

// Devuelve { vc, letra, fn, fz, amg, validoEnCatalogo } exactos del catálogo Dormer
function getDormerParams(mat, toolCode, diam = 10) {
    const amg = MAP_CMC_TO_DORMER[mat.cmc] || "1.2";
    const tool = DB_DORMER_HERRAMIENTAS[toolCode];
    if (tool && tool.amg && tool.amg[amg]) {
        const parsed = parseDormerCode(tool.amg[amg]);
        if (parsed) {
            let fn = 0.1,
                fz = 0.05;
            if (tool.tipo === "mecha") {
                fn = interpolarPorDiametro(diam, DORMER_DIAMS_FN, DORMER_TABLA_FN_MECHAS[parsed.letra]) || 0.1;
                fz = Number((fn / 2).toFixed(3));
            } else if (tool.factor === "HM") {
                fz = interpolarPorDiametro(diam, DORMER_DIAMS_FZ_HM, DORMER_TABLA_FZ_HM[parsed.letra]) || 0.05;
                fn = Number((fz * (tool.zn || 2)).toFixed(3));
            } else {
                fz = interpolarPorDiametro(diam, DORMER_DIAMS_FZ_HSS, DORMER_TABLA_FZ_HSS[parsed.letra]) || 0.05;
                fn = Number((fz * (tool.zn || 2)).toFixed(3));
            }
            return { vc: parsed.vc, letra: parsed.letra, fn, fz, amg, validoEnCatalogo: true };
        }
    }
    // Fallback si una herramienta no tiene recomendación directa para ese AMG en la tabla
    const baseVc =
        {
            1.1: 30,
            1.2: 28,
            1.3: 25,
            1.4: 22,
            1.5: 15,
            1.6: 10,
            1.7: 8,
            1.8: 6,
            2.1: 20,
            2.2: 12,
            2.3: 14,
            2.4: 10,
            3.1: 28,
            3.2: 22,
            3.3: 20,
            3.4: 15,
            4.1: 20,
            4.2: 12,
            4.3: 6,
            5.1: 12,
            5.2: 8,
            5.3: 4,
            7.1: 50,
            7.2: 45,
            7.3: 35,
            7.4: 25,
        }[amg] || 20;
    const mult = tool?.factor === "HM" ? 2.5 : tool?.factor === "HSS-E-PM" ? 1.3 : 1.0;
    return { vc: Math.round(baseVc * mult), letra: "-", fn: 0.1, fz: 0.05, amg, validoEnCatalogo: false };
}

function getDormerVc(mat, toolCode, diam = 10) {
    return getDormerParams(mat, toolCode, diam).vc;
}

function getDormerFnMecha(mat, toolCode, diam = 10) {
    return getDormerParams(mat, toolCode, diam).fn;
}

function getDormerFzFresa(mat, toolCode, diam = 10) {
    return getDormerParams(mat, toolCode, diam).fz;
}

function getDormerToolInfo(code) {
    return DB_DORMER_HERRAMIENTAS[code] || null;
}

function getHerramientasDormerPorTipo(tipo) {
    return Object.entries(DB_DORMER_HERRAMIENTAS)
        .filter(([code, t]) => t.tipo === tipo)
        .map(([code, t]) => ({ code, ...t }));
}

// Helper de Vc universal (Sandvik o Dormer)
function getVcPorCatalogo(mat, catalogo, toolCode, empane, diam = 10) {
    if (catalogo === "dormer") {
        return getDormerVc(mat, toolCode, diam);
    }
    return empane === "mucho" ? mat.vc_mucho : mat.vc_poco;
}
