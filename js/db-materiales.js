// DIÁMETROS COMERCIALES DE MECHA (mm) — Serie preferida ISO
// ============================================================
const DIAMETROS_MECHA_COMERCIALES = [3, 4, 5, 6, 8, 10, 12, 14, 16, 18, 20, 22, 25, 28, 30, 32, 35, 38, 40, 45, 50, 55, 60];

// ============================================================
// SECUENCIA DE MECHAS PARA UN AGUJERO FINAL
// Regla: cada mecha previa ≈ 60% del diámetro de la siguiente.
// Máximo 2 mechas previas (3 totales) — alcanza para el alcance del curso.
// ============================================================
function calcularSecuenciaMechas(diamFinal) {
    if (!diamFinal || diamFinal <= 6) return [{ d: diamFinal, tipo: "final" }];
    const seq = [];
    let actual = diamFinal;
    let intentos = 0;
    while (actual > 6 && intentos < 2) {
        const objetivo = actual * 0.6;
        let previa = null;
        for (const d of DIAMETROS_MECHA_COMERCIALES) {
            if (d >= actual * 0.8) break;
            if (d <= objetivo) previa = d;
        }
        if (!previa || previa >= actual * 0.8) break;
        seq.unshift({ d: previa, tipo: "previa" });
        actual = previa;
        intentos++;
    }
    seq.push({ d: diamFinal, tipo: "final" });
    return seq;
}

